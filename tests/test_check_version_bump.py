"""scripts/check_version_bump.py: patch +1 from the base, lock agrees.

These cases fail if the script is missing or if a minor bump, a skipped
src/ bump, or a Cargo.lock mismatch is accepted.
"""

from __future__ import annotations

import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from tests.git_env import without_hook_git

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "check_version_bump.py"


def git(cwd: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=cwd,
        check=True,
        capture_output=True,
        text=True,
        env=without_hook_git(),
    )
    return result.stdout


def write_crate(repo: Path, version: str) -> None:
    (repo / "Cargo.toml").write_text(
        "[package]\n"
        'name = "recall"\n'
        f'version = "{version}"\n'
        'edition = "2021"\n',
        encoding="utf-8",
    )
    (repo / "Cargo.lock").write_text(
        "\n".join(
            [
                "# This file is automatically @generated by Cargo.",
                "version = 4",
                "",
                "[[package]]",
                'name = "recall"',
                f'version = "{version}"',
                "",
            ]
        ),
        encoding="utf-8",
    )


def init_repo(path: Path, version: str = "0.7.3") -> Path:
    path.mkdir(parents=True)
    git(path, "init", "-q", "-b", "main")
    git(path, "config", "user.name", "recall contributors")
    git(path, "config", "user.email", "contributors@recall.invalid")
    write_crate(path, version)
    (path / "README.md").write_text("base\n", encoding="utf-8")
    git(path, "add", "Cargo.toml", "Cargo.lock", "README.md")
    git(path, "commit", "-q", "-m", "base")
    git(path, "update-ref", "refs/remotes/origin/main", "HEAD")
    return path


def run_check(
    repo: Path,
    *args: str,
    env: dict[str, str] | None = None,
) -> subprocess.CompletedProcess[str]:
    merged = without_hook_git()
    merged.pop("RECALL_SEMVER_LABEL", None)
    if env:
        merged.update(env)
    return subprocess.run(
        ["python3", str(SCRIPT), "--repo", str(repo), *args],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
        env=merged,
    )


class CheckVersionBumpTests(unittest.TestCase):
    def test_src_diff_error_is_not_treated_as_no_change(self) -> None:
        import importlib.util

        spec = importlib.util.spec_from_file_location("check_version_bump", SCRIPT)
        assert spec is not None and spec.loader is not None
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "diff-err")
            changed, err = mod._src_diff(repo, "deadbeef", "HEAD")
            self.assertFalse(changed)
            self.assertIsNotNone(err)
            assert err is not None
            self.assertIn("git diff failed", err)

    def test_script_exists(self) -> None:
        self.assertTrue(SCRIPT.is_file(), "add scripts/check_version_bump.py")

    def test_patch_bump_with_src_change_passes(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "ok")
            src = repo / "src"
            src.mkdir()
            (src / "lib.rs").write_text("fn main() {}\n", encoding="utf-8")
            write_crate(repo, "0.7.4")
            git(repo, "add", "src/lib.rs", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "patch")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("version-bump: ok", result.stdout)

    def test_capture_helper_change_does_not_require_a_bump(self) -> None:
        """The hard bump rule is src/ only. capture-helper stays on the warning script."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "helper")
            helper = repo / "capture-helper"
            helper.mkdir()
            (helper / "main.swift").write_text("print(1)\n", encoding="utf-8")
            git(repo, "add", "capture-helper/main.swift")
            git(repo, "commit", "-q", "-m", "helper")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 0, result.stderr)

    def test_second_patch_bump_must_follow_the_current_base(self) -> None:
        """Two branches that both take 0.7.4: the later one must become 0.7.5."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "race")
            git(repo, "checkout", "-q", "-b", "first")
            write_crate(repo, "0.7.4")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "first bump")
            git(repo, "checkout", "-q", "main")
            write_crate(repo, "0.7.4")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "other pr merged")
            git(repo, "update-ref", "refs/remotes/origin/main", "HEAD")
            git(repo, "checkout", "-q", "first")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            self.assertIn("0.7.4", result.stderr)
            self.assertIn("0.7.5", result.stderr)

    def test_labeled_minor_collision_names_next_minor_not_patch(self) -> None:
        """A minor collision must name the next minor, not the next patch."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "minor-race")
            git(repo, "checkout", "-q", "-b", "first")
            write_crate(repo, "0.8.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "minor bump")
            git(repo, "checkout", "-q", "main")
            write_crate(repo, "0.8.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "other minor merged")
            git(repo, "update-ref", "refs/remotes/origin/main", "HEAD")
            git(repo, "checkout", "-q", "first")
            result = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                "--labels",
                "semver:minor",
            )
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            self.assertIn("0.9.0", result.stderr)
            self.assertNotIn("0.8.1", result.stderr)

    def test_src_change_without_bump_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "nobump")
            src = repo / "src"
            src.mkdir()
            (src / "lib.rs").write_text("fn main() {}\n", encoding="utf-8")
            git(repo, "add", "src/lib.rs")
            git(repo, "commit", "-q", "-m", "src only")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 1, result.stdout)
            self.assertIn("src/", result.stderr)
            self.assertIn("0.7.4", result.stderr)

    def test_minor_bump_without_label_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "minor")
            write_crate(repo, "0.8.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "minor")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 1, result.stdout)
            joined = result.stderr.lower()
            self.assertTrue("patch" in joined or "0.8.0" in joined, result.stderr)
            self.assertIn("semver:minor", result.stderr)

    def test_minor_bump_with_label_passes(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "minor-ok")
            src = repo / "src"
            src.mkdir()
            (src / "lib.rs").write_text("fn changed() {}\n", encoding="utf-8")
            write_crate(repo, "0.8.0")
            git(repo, "add", "src/lib.rs", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "minor")
            result = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                "--labels",
                "semver:minor",
            )
            self.assertEqual(result.returncode, 0, result.stderr)

    def test_major_bump_needs_major_label(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "major")
            write_crate(repo, "1.0.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "major")
            denied = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                "--labels",
                "semver:minor",
            )
            self.assertEqual(denied.returncode, 1, denied.stderr)
            allowed = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                "--labels",
                "semver:major",
            )
            self.assertEqual(allowed.returncode, 0, allowed.stderr)

    def test_patch_plus_two_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "jump")
            write_crate(repo, "0.7.5")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "jump")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 1, result.stdout)

    def test_lock_must_agree(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "lock")
            (repo / "Cargo.toml").write_text(
                '[package]\nname = "recall"\nversion = "0.7.4"\nedition = "2021"\n',
                encoding="utf-8",
            )
            git(repo, "add", "Cargo.toml")
            git(repo, "commit", "-q", "-m", "toml only")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 1, result.stdout)
            self.assertIn("Cargo.lock", result.stderr)

    def test_unchanged_version_without_src_change_passes(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "docs")
            (repo / "README.md").write_text("docs\n", encoding="utf-8")
            git(repo, "add", "README.md")
            git(repo, "commit", "-q", "-m", "docs")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 0, result.stderr)

    def test_main_moving_does_not_count_as_a_branch_src_change(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "move")
            git(repo, "checkout", "-q", "-b", "feature")
            (repo / "README.md").write_text("feature\n", encoding="utf-8")
            git(repo, "add", "README.md")
            git(repo, "commit", "-q", "-m", "feature docs")
            git(repo, "checkout", "-q", "main")
            src = repo / "src"
            src.mkdir()
            (src / "lib.rs").write_text("fn on_main() {}\n", encoding="utf-8")
            git(repo, "add", "src/lib.rs")
            git(repo, "commit", "-q", "-m", "main src")
            git(repo, "update-ref", "refs/remotes/origin/main", "HEAD")
            git(repo, "checkout", "-q", "feature")
            result = run_check(repo, "--base", "origin/main", "--head", "HEAD", "--labels", "")
            self.assertEqual(result.returncode, 0, result.stderr + result.stdout)

    def test_explicit_labels_ignore_the_local_env_var(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "env")
            write_crate(repo, "0.8.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "minor")
            result = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                "--labels",
                "",
                env={"RECALL_SEMVER_LABEL": "semver:minor"},
            )
            self.assertEqual(result.returncode, 1, result.stderr)

    def test_local_env_var_allows_a_minor_bump_when_labels_are_omitted(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "local-env")
            write_crate(repo, "0.8.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "minor")
            result = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                env={"RECALL_SEMVER_LABEL": "semver:minor"},
            )
            self.assertEqual(result.returncode, 0, result.stderr)

    def test_staged_lock_mismatch_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "staged")
            (repo / "Cargo.toml").write_text(
                '[package]\nname = "recall"\nversion = "0.7.4"\nedition = "2021"\n',
                encoding="utf-8",
            )
            git(repo, "add", "Cargo.toml")
            result = run_check(repo, "--staged")
            self.assertEqual(result.returncode, 1, result.stdout)
            self.assertIn("Cargo.lock", result.stderr)

    def test_event_file_label_allows_minor_and_ignores_env(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "event")
            write_crate(repo, "0.8.0")
            git(repo, "add", "Cargo.toml", "Cargo.lock")
            git(repo, "commit", "-q", "-m", "minor")
            event = Path(tmp) / "event.json"
            event.write_text(
                '{"pull_request":{"labels":[{"name":"semver:minor"}]}}\n',
                encoding="utf-8",
            )
            result = run_check(
                repo,
                "--base",
                "origin/main",
                "--head",
                "HEAD",
                "--event-file",
                str(event),
                env={"RECALL_SEMVER_LABEL": ""},
            )
            self.assertEqual(result.returncode, 0, result.stderr)

    def test_staged_with_no_crate_files_passes(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            repo = init_repo(Path(tmp) / "staged-ok")
            (repo / "README.md").write_text("more\n", encoding="utf-8")
            git(repo, "add", "README.md")
            result = run_check(repo, "--staged")
            self.assertEqual(result.returncode, 0, result.stderr)


